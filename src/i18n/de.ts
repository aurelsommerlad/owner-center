/**
 * Widens every string-literal leaf of `typeof de` (which `as const` makes
 * exact, e.g. the literal type "E-Mail") to plain `string`, while keeping
 * every group/key required. Without this, `Dictionary` would demand that
 * `en.ts` literally re-type each German string - the widened `Dictionary`
 * still catches a missing/extra key (TypeScript's excess-property check on
 * `en`'s object literal), just not the field's exact wording.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };

export type Dictionary = Widen<typeof de>;
